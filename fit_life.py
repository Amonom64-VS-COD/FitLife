WATER_PER_KG = 30
ML_IN_LITER = 1000

# Знакомство с пользователем.
print("Доброго времени суток. Давайте знакомиться.", end=" ")
print("Меня зовут FitLife. Я буду вашим фитнес-помощником.", end=" ")
user_name = input("Подскажите, как вас зовут? ")
user_age = int(input(
    f"Приятно познакомиться, {user_name}! Сколько вам полных лет? "))

# Узнаём вес и рост пользователя.
user_weight = float(input(
    f"{user_name}, прошу вас указать ваш вес в кг. "
    "И просим вас дробную часть отделять именно точкой, а не запятой. "
    "(например, 75.5): "))
user_height = float(input(
    "И так же прошу вас указать ваш рост в метрах. "
    "И также просим вас дробную часть отделять именно точной, а не запятой. "
    "(например, 1.75): "))

# Расчёт индекса массы тела (ИМТ\bmi)
bmi = round(user_weight / (user_height ** 2), 1)

# Расчёт нормы воды в день, в миллилитрах и литрах.
water_ml = user_weight * WATER_PER_KG
water_l = round(water_ml / ML_IN_LITER, 3)

# Вывод результатов
print(f"Отчет для пользователя: {user_name} ({user_age} г.)")
print(f"Твой Индекс Массы Тела: {bmi}")
print(f"Рекомендуемая норма воды: {water_l} л. в день.")
print()
print("Расчет окончен. Будьте здоровы!")
